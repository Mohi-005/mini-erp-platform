export function searchCatalogue(
  query: string,
  options?: { includeRestricted?: boolean; limit?: number; category?: string },
): CatalogueProduct[] {
  const rawQ = (query || '').trim().toLowerCase();
  const q = rawQ.normalize('NFC');
  if (!rawQ) return [];
  const limit = options?.limit ?? 20;
  const includeRestricted = options?.includeRestricted ?? false;
  const catFilter = options?.category;

  const matches = CANONICAL_283_CATALOGUE.filter((item) => {
    if (!includeRestricted && item.is_restricted) return false;
    if (catFilter && item.category_bn !== catFilter) return false;
    const nameBnRaw = item.name_bn.toLowerCase();
    const nameBnNfc = nameBnRaw.normalize('NFC');
    const nameEn = (item.name_en || '').toLowerCase();
    const nameBg = (item.name_banglish || '').toLowerCase();
    const sku = item.sku.toLowerCase();
    const code = item.code.toLowerCase();
    return (
      nameBnRaw.includes(rawQ) ||
      nameBnNfc.includes(q) ||
      nameEn.includes(rawQ) ||
      nameBg.includes(rawQ) ||
      sku.includes(rawQ) ||
      code.includes(rawQ)
    );
  });

  matches.sort((a, b) => {
    const aNameRaw = a.name_bn.toLowerCase();
    const aNameNfc = aNameRaw.normalize('NFC');
    const bNameRaw = b.name_bn.toLowerCase();
    const bNameNfc = bNameRaw.normalize('NFC');
    const aPrefix =
      aNameRaw.startsWith(rawQ) ||
      aNameNfc.startsWith(q) ||
      (a.name_en && a.name_en.toLowerCase().startsWith(rawQ)) ||
      (a.name_banglish && a.name_banglish.toLowerCase().startsWith(rawQ))
        ? 0
        : 1;
    const bPrefix =
      bNameRaw.startsWith(rawQ) ||
      bNameNfc.startsWith(q) ||
      (b.name_en && b.name_en.toLowerCase().startsWith(rawQ)) ||
      (b.name_banglish && b.name_banglish.toLowerCase().startsWith(rawQ))
        ? 0
        : 1;
    return aPrefix - bPrefix;
  });

  return matches.slice(0, limit);
}

export const DEFAULT_SUPABASE_STORAGE_URL =
  'https://jujwnhwrktmimtcnljsd.supabase.co';
export const CATALOGUE_STORAGE_BUCKET = 'catalogue-images';

// Fast index lookups for canonical products
const CANONICAL_BY_CODE = new Map<string, CatalogueProduct>();
const CANONICAL_BY_SKU = new Map<string, CatalogueProduct>();
const CANONICAL_BY_NAME_BN = new Map<string, CatalogueProduct>();

for (const item of CANONICAL_283_CATALOGUE) {
  if (item.code) CANONICAL_BY_CODE.set(item.code.trim().toLowerCase(), item);
  if (item.sku) CANONICAL_BY_SKU.set(item.sku.trim().toLowerCase(), item);
  if (item.name_bn) {
    CANONICAL_BY_NAME_BN.set(item.name_bn.trim().toLowerCase(), item);
    CANONICAL_BY_NAME_BN.set(
      item.name_bn.trim().normalize('NFC').toLowerCase(),
      item,
    );
  }
}

/**
 * Builds the public Supabase Storage URL for a given catalogue image path.
 */
export function getCatalogueImageUrl(
  imagePath?: string | null,
  baseUrl?: string | null,
): string | null {
  if (!imagePath || typeof imagePath !== 'string') return null;
  const trimmed = imagePath.trim();
  if (!trimmed) return null;

  if (trimmed.startsWith('http://') || trimmed.startsWith('https://')) {
    return trimmed;
  }

  const base =
    (baseUrl || '').trim().replace(/\/+$/, '') || DEFAULT_SUPABASE_STORAGE_URL;
  const cleanPath = trimmed.replace(/^\/+/, '');
  return `${base}/storage/v1/object/public/${CATALOGUE_STORAGE_BUCKET}/${cleanPath}`;
}

/**
 * Resolves a canonical catalogue product from candidate identifiers
 * (code, sku, or Bengali name).
 */
export function findCanonicalProduct(
  candidate?: {
    code?: string | null;
    sku?: string | null;
    name_bn?: string | null;
    name_en?: string | null;
    name_banglish?: string | null;
  } | null,
): CatalogueProduct | null {
  if (!candidate) return null;

  if (candidate.code) {
    const byCode = CANONICAL_BY_CODE.get(candidate.code.trim().toLowerCase());
    if (byCode) return byCode;
  }

  if (candidate.sku) {
    const skuKey = candidate.sku.trim().toLowerCase();
    const bySku = CANONICAL_BY_SKU.get(skuKey);
    if (bySku) return bySku;

    // In case SKU was passed as CATV2-xxx directly
    const byCode = CANONICAL_BY_CODE.get(skuKey);
    if (byCode) return byCode;
  }

  if (candidate.name_bn) {
    const rawKey = candidate.name_bn.trim().toLowerCase();
    const byName = CANONICAL_BY_NAME_BN.get(rawKey);
    if (byName) return byName;
    const nfcKey = candidate.name_bn.trim().normalize('NFC').toLowerCase();
    const byNfc = CANONICAL_BY_NAME_BN.get(nfcKey);
    if (byNfc) return byNfc;
  }

  return null;
}

/**
 * Resolves the public image URL for a product, cart line, or catalogue item.
 * Checks for direct image_path first, then matches against the 283 canonical catalogue items.
 */
export function getProductImageUrl(
  product?: {
    image_path?: string | null;
    code?: string | null;
    sku?: string | null;
    name_bn?: string | null;
    name_en?: string | null;
    name_banglish?: string | null;
  } | null,
  baseUrl?: string | null,
): string | null {
  if (!product) return null;

  if (product.image_path) {
    return getCatalogueImageUrl(product.image_path, baseUrl);
  }

  const canonical = findCanonicalProduct(product);
  if (canonical && canonical.image_path) {
    return getCatalogueImageUrl(canonical.image_path, baseUrl);
  }

  return null;
}
